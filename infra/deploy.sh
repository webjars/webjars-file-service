#!/usr/bin/env bash
# Create/update the S3 bucket + IAM user stack and hand its credentials to the
# service.
#
#   infra/deploy.sh local            # writes .env.local (gitignored) for `./sbta Test/run`
#   infra/deploy.sh prod             # sets config vars on the Heroku app (restarts it)
#   infra/deploy.sh <env> --rotate   # also replaces the access key
#
# Needs pkl, the AWS CLI (override with AWS="nix run nixpkgs#awscli2 --") and,
# for prod, the Heroku CLI. Uses whatever AWS credentials the CLI resolves.
set -euo pipefail

env_name="${1:?usage: deploy.sh <local|prod> [--rotate]}"
rotate="${2:-}"
case "$env_name" in local|prod) ;; *) echo "env must be local or prod" >&2; exit 2 ;; esac
[[ -z "$rotate" || "$rotate" == "--rotate" ]] || { echo "unknown option: $rotate" >&2; exit 2; }

infra_dir="$(cd "$(dirname "$0")" && pwd)"
root_dir="$(dirname "$infra_dir")"
region="${AWS_DEPLOY_REGION:-us-east-1}"   # same region as Heroku's US dynos: free S3 transfer
stack="webjars-file-service-$env_name"
heroku_app="${HEROKU_APP:-webjars-file-service}"
local_env_file="$root_dir/.env.local"
read -r -a aws <<< "${AWS:-aws}"
aws() { "${aws[@]}" --region "$region" "$@"; }

(cd "$infra_dir" && pkl eval aws.pkl -f yaml -o aws.yaml)

aws cloudformation deploy \
  --stack-name "$stack" \
  --template-file "$infra_dir/aws.yaml" \
  --capabilities CAPABILITY_IAM \
  --no-fail-on-empty-changeset

output() {
  aws cloudformation describe-stacks --stack-name "$stack" \
    --query "Stacks[0].Outputs[?OutputKey=='$1'].OutputValue" --output text
}
bucket="$(output BucketName)"
user="$(output UserName)"
bucket_region="$(output Region)"

# The key the target currently uses, if any.
case "$env_name" in
  prod)  current_key="$(heroku config:get AWS_ACCESS_KEY_ID -a "$heroku_app")" ;;
  local) current_key="$( [[ -f "$local_env_file" ]] && sed -n 's/^export AWS_ACCESS_KEY_ID=//p' "$local_env_file" || true)" ;;
esac

user_keys="$(aws iam list-access-keys --user-name "$user" --query 'AccessKeyMetadata[].AccessKeyId' --output text)"
key_is_users=false
for k in $user_keys; do [[ "$k" == "$current_key" ]] && key_is_users=true; done

set_target() { # <key id> <secret, or empty to leave unchanged>
  case "$env_name" in
    prod)
      local vars=(S3_BUCKET="$bucket" AWS_REGION="$bucket_region")
      [[ -n "$2" ]] && vars+=(AWS_ACCESS_KEY_ID="$1" AWS_SECRET_ACCESS_KEY="$2")
      heroku config:set -a "$heroku_app" "${vars[@]}" > /dev/null
      ;;
    local)
      local secret="$2"
      [[ -z "$secret" ]] && secret="$(sed -n 's/^export AWS_SECRET_ACCESS_KEY=//p' "$local_env_file")"
      (umask 077 && cat > "$local_env_file" <<EOF
# Generated by infra/deploy.sh local. Use with: set -a; . ./.env.local; set +a
export S3_BUCKET=$bucket
export AWS_REGION=$bucket_region
export AWS_ACCESS_KEY_ID=$1
export AWS_SECRET_ACCESS_KEY=$secret
EOF
      )
      ;;
  esac
}

if $key_is_users && [[ -z "$rotate" ]]; then
  set_target "$current_key" ""
  echo "$stack: bucket=$bucket user=$user; kept access key $current_key"
else
  # IAM allows two keys per user: drop any the target isn't using first.
  for k in $user_keys; do
    [[ "$k" == "$current_key" ]] || aws iam delete-access-key --user-name "$user" --access-key-id "$k"
  done
  read -r new_key new_secret < <(aws iam create-access-key --user-name "$user" \
    --query 'AccessKey.[AccessKeyId,SecretAccessKey]' --output text)
  # Switch the target before deleting its old key so it never holds a dead one.
  set_target "$new_key" "$new_secret"
  if $key_is_users; then
    aws iam delete-access-key --user-name "$user" --access-key-id "$current_key"
  fi
  echo "$stack: bucket=$bucket user=$user; new access key $new_key"
fi
